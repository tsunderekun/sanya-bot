IMAGE_REQUEST_PATTERN = re.compile(
    r"(скинь|покажи|найди|отправь|кинь|вруби|дай|запили)\s+.*(картинк|фотк|пикч|фото|изображен|мем|скрин|поняш|пони|коня|коней|видюх|мать|плату|проц|роутер)|"
    r"как выглядит\s+([a-zA-Zа-яА-Я0-9\s_\-]+)|"
    r"^/(img|pic|image|photo|картинка|пикча)\b",
    re.IGNORECASE,
)


class Mode(Enum):
    CHAT = "chat"
    DETAIL = "detail"
    CODE = "code"
    PROMPT = "prompt"


PROMPT_REQUEST = re.compile(
    r"\b(?:напиши|дай|скинь|составь|сделай|набросай|какой|посоветуй|накидай)\s+(?:[^\n?!]{0,80}?)\b(?:промпт|промт|prompt)\b|"
    r"^(?:промпт|промт|prompt)\s+(?:для|на|под|for)\b|"
    r"\b(?:write|give|draft|generate|create)\b[^\n?!]{0,80}\bprompt\b",
    re.I,
)
CODE_FOLLOWUP = re.compile(
    r"^(?:накидывай|накидай|давай|пиши|делай|скинь|кидай|жги|продолжай|допиши|кинь)\b",
    re.I,
)
CODE_CONTEXT = re.compile(
    r"```|\b(?:скрипт\w*|код\w*|python|питон\w*|bash|баш\w*|макрос\w*)\b", re.I
)
ENGLISH_CODE = re.compile(
    r"\b(?:write|generate|create|draft|implement|give|show)\b[^\n?!]{0,100}\b(?:script|program|code|function|macro|python|bash|javascript|powershell)\b",
    re.I,
)


def classify_intent(text: str, quoted: str = "") -> Mode:
    if PROMPT_REQUEST.search(text):
        return Mode.PROMPT
    if (
        CODING_TRIGGER_PATTERN.search(text)
        or ENGLISH_CODE.search(text)
        or (CODE_FOLLOWUP.search(text) and CODE_CONTEXT.search(quoted))
    ):
        return Mode.CODE
    if DETAILED_REQUEST_PATTERN.search(text):
        return Mode.DETAIL
    return Mode.CHAT


def may_search(mode: Mode, *, enabled: bool, insult: bool) -> bool:
    return enabled and not insult and mode not in (Mode.CODE, Mode.PROMPT)
