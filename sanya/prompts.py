def build_system_prompt(
    mode: Mode,
    context: str = "",
    *directives: str,
    rofl: bool = False,
    style: ReplyStyle = ReplyStyle(),
    explicit_lore: bool = False,
) -> str:
    parts = [
        SYSTEM_PROMPT,
        "Помеченные как вымысел реплики из истории не являются фактами.",
    ]
    if mode in (Mode.CHAT, Mode.DETAIL):
        parts.append(SOCIAL)
        if _AI_TOPIC.search(context[:2000]) and random() < 0.10:
            parts.append(_AI_EXPERT)
    if mode is not Mode.CODE:
        text = context[:2000]
        matches = [
            (match.start(), lore)
            for pattern, lore, technical in TOPICS
            if (mode is not Mode.PROMPT or lore.startswith("Саня брони"))
            and (style.lore > 0 or explicit_lore or technical or mode is Mode.PROMPT)
            and (match := pattern.search(text))
        ]
        parts.extend(
            lore
            for _, lore in sorted(matches, key=lambda item: item[0])[
                : 3 + (style.lore == 3)
            ]
        )
    parts.append(MODE_PROMPTS[mode])
    if rofl and mode in (Mode.CHAT, Mode.DETAIL):
        parts.append(ROFL_PROMPT if style.lore else ROFL_PROMPT.split("\n", 1)[0])
    if mode in (Mode.CHAT, Mode.DETAIL):
        parts.extend(filter(None, (_TONE_STYLE[style.tone], _LORE_STYLE[style.lore])))
    parts.extend(filter(None, directives))
    return "\n\n".join(parts)
